#!/usr/bin/env python3
"""Write web/js/fleet.js from data/fleet_models.json.

Each model: type (tram/trolley/bus), model name, fleet-number ranges, features,
and body geometry (section lengths in metres; `coupled` for trams that run as
pairs). The lookup tries the vehicle's own type first, then the others: some
battery buses run on trolleybus lines and carry TB-prefixed ids.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
models = json.loads((ROOT / "data" / "fleet_models.json").read_text(encoding="utf-8"))
out = []
for m in models["models"]:
    out.append({k: m[k] for k in ("type", "model", "ranges", "low_floor", "ac", "sections", "coupled", "years", "length_m", "propulsion") if m.get(k) is not None})
js = """/* Sofia fleet: vehicle models by fleet number. Generated by pipeline/tools/build_fleet.py
 * from data/fleet_models.json (see the sources listed there). */
(function () {
  "use strict";
  const MODELS = %s;
  const ORDER = { tram: ["tram", "trolley", "bus"], trolley: ["trolley", "bus", "tram"], bus: ["bus", "trolley", "tram"] };
  // Within a vehicle type the narrowest matching range wins, so exceptions inside a
  // wider batch (e.g. Karsan minibuses 2501-2505 inside BMC 2500-2599) resolve correctly.
  function lookup(type, num) {
    for (const ty of ORDER[type] || ORDER.bus) {
      let best = null, width = Infinity;
      for (const m of MODELS) {
        if (m.type !== ty) continue;
        for (const [a, b] of m.ranges) if (a <= num && num <= b && b - a < width) { best = m; width = b - a; }
      }
      if (best) return best;
    }
    return null;
  }
  window.FLEET = { MODELS, lookup };
})();
""" % json.dumps(out, ensure_ascii=False, separators=(",", ":"))
(ROOT / "web" / "js" / "fleet.js").write_text(js, encoding="utf-8")
print(f"{len(out)} models -> web/js/fleet.js")
